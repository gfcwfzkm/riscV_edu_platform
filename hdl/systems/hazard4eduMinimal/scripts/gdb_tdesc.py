#!/usr/bin/env python3
"""Write a gdb target description that lists only the registers the SoC can actually read.

OpenOCD describes every CSR it knows to gdb, including many that Hazard3 does not implement
(vector, hypervisor, supervisor, PMP, ...). Reading one of those fails ("Could not fetch register
"vcsr"; remote failure reply '0E'"), and debuggers that fetch all registers at once, such as the
VS Code register views, then fail completely. This script asks the running SoC for OpenOCD's target
description, tries to read every register, and writes the description without the unreadable ones.
gdb loads it with "set tdesc filename <file>" before connecting; the register numbers stay those of
OpenOCD, so nothing else changes.

Usage (with the bitstream loaded and no other OpenOCD running):
    gdb_tdesc.py --openocd <openocd> --config <openocd .cfg> --gdb <gdb> --output <file.xml>
"""
import argparse
import re
import subprocess
import sys
import time


def run_gdb(gdb, port, commands, timeout=60):
    args = [gdb, "-q", "-batch", "-nx", "-ex", "set architecture riscv:rv32",
            "-ex", f"target extended-remote localhost:{port}"]
    for command in commands:
        args += ["-ex", command]
    result = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    return result.stdout + result.stderr


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--openocd", required=True)
    parser.add_argument("--config", required=True)
    parser.add_argument("--gdb", default="gdb")
    parser.add_argument("--port", type=int, default=3333)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    openocd = subprocess.Popen([args.openocd, "-f", args.config, "-c", f"gdb_port {args.port}"],
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    log = []
    try:
        deadline = time.time() + 20
        while time.time() < deadline:
            line = openocd.stdout.readline()
            if not line:
                break
            log.append(line)
            if f"Listening on port {args.port} for gdb connections" in line:
                break
        else:
            line = ""
        if not any(f"port {args.port} for gdb" in l for l in log):
            sys.exit("OpenOCD did not start:\n" + "".join(log[-10:]))

        # halt so that every register can be read, then let the program continue
        out = run_gdb(args.gdb, args.port, ["monitor halt", "maint print xml-tdesc",
                                            "info all-registers", "monitor resume", "detach"])
    finally:
        openocd.terminate()
        try:
            openocd.wait(timeout=5)
        except subprocess.TimeoutExpired:
            openocd.kill()

    start = out.find("<?xml")
    end = out.find("</target>")
    if start < 0 or end < 0:
        sys.exit("no target description from gdb:\n" + out[-2000:])
    xml = out[start:end + len("</target>")]
    unreadable = set(re.findall(r'^(\S+)\s+Could not fetch register', out, flags=re.M))
    regs = re.findall(r'<reg name="([^"]+)"', xml)
    if not regs:
        sys.exit("target description without registers")

    kept = []
    for line in xml.splitlines():
        match = re.search(r'<reg name="([^"]+)"', line)
        if match and match.group(1) in unreadable:
            continue
        kept.append(line)
    header = ("<!-- Generated by scripts/gdb_tdesc.py (make gdb-tdesc): OpenOCD's target description of\n"
              "     hazard4eduMinimal without the registers the SoC cannot read. Load it in gdb with\n"
              "     'set tdesc filename <this file>' before connecting. -->")
    kept.insert(2 if kept[1].startswith("<!DOCTYPE") else 1, header)
    with open(args.output, "w") as f:
        f.write("\n".join(kept) + "\n")
    print(f"{args.output}: {len(regs) - len(unreadable)} of {len(regs)} registers kept, "
          f"{len(unreadable)} unreadable removed")


if __name__ == "__main__":
    main()
